"""Small inline SVG line charts of the economy lab's first run, for the phone page.

Reads `economy/report-data.json` (generated by `packages/econ`). Each chart has one axis, a legend,
direct labels on line ends, and a <title> on every point for hover. Colours: the dark-surface
categorical order from the dataviz palette (blue, orange, aqua, yellow, magenta), fixed per series.
"""
import html
import json
import os

SERIES = ['#3987e5', '#d95926', '#199e70', '#c98500', '#d55181']
W, H = 340, 190
L, R, T, B = 34, 54, 10, 24


def _line_chart(title, note, series, ymax, yticks, yfmt=str, ref=None, short=None):
    """series: [(label, [value per week 1..n])]; ref: (label, [values]) drawn dashed in muted ink."""
    n = max(len(v) for _, v in series)
    x = lambda i: L + (W - L - R) * i / (n - 1)
    y = lambda v: T + (H - T - B) * (1 - min(v, ymax) / ymax)
    out = [f'<figure class="chart"><figcaption><strong>{html.escape(title)}</strong>'
           f'<span>{html.escape(note)}</span></figcaption>'
           f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="{html.escape(title)}">']
    for t in yticks:
        out.append(f'<line class="grid" x1="{L}" x2="{W - R}" y1="{y(t):.1f}" y2="{y(t):.1f}"/>'
                   f'<text class="tick" x="{L - 4}" y="{y(t) + 3:.1f}" text-anchor="end">{yfmt(t)}</text>')
    for wk in (1, 4, 8, 12, 16, 20, 24):
        if wk <= n:
            out.append(f'<text class="tick" x="{x(wk - 1):.1f}" y="{H - 8}" text-anchor="middle">{wk}</text>')
    out.append(f'<text class="tick" x="{W - R + 12}" y="{H - 8}">week</text>')
    if ref:
        pts = ' '.join(f'{x(i):.1f},{y(v):.1f}' for i, v in enumerate(ref[1]) if v is not None)
        out.append(f'<polyline class="ref" points="{pts}"/>')
    ends = []
    for k, (label, vals) in enumerate(series):
        c = SERIES[k]
        pts = ' '.join(f'{x(i):.1f},{y(v):.1f}' for i, v in enumerate(vals))
        out.append(f'<polyline class="line" stroke="{c}" points="{pts}"/>')
        for i, v in enumerate(vals):
            out.append(f'<circle class="hit" cx="{x(i):.1f}" cy="{y(v):.1f}" r="5">'
                       f'<title>{html.escape(label)}, week {i + 1}: {yfmt(round(v, 1))}</title></circle>')
        ends.append([y(vals[-1]), short[k] if short else label.split(' ')[0], c])
    ends.sort()
    for i in range(1, len(ends)):  # keep end labels at least 11px apart
        ends[i][0] = max(ends[i][0], ends[i - 1][0] + 11)
    for ey, label, c in ends:
        out.append(f'<text class="end" x="{W - R + 4}" y="{ey + 3:.1f}">{html.escape(label)}</text>')
    out.append('</svg><div class="legend">')
    for k, (label, _) in enumerate(series):
        out.append(f'<span><i class="sw" data-c="{k}"></i>{html.escape(label)}</span>')
    if ref:
        out.append(f'<span><i class="sw ref"></i>{html.escape(ref[0])}</span>')
    out.append('</div></figure>')
    return ''.join(out)


def _split_bars(title, note, rows, labels):
    """rows: [(name, [share per part])] as horizontal 100% bars; labels name the parts."""
    bh, gap, lw = 16, 8, 92
    h = len(rows) * (bh + gap) + 4
    out = [f'<figure class="chart"><figcaption><strong>{html.escape(title)}</strong>'
           f'<span>{html.escape(note)}</span></figcaption><svg viewBox="0 0 {W} {h}" role="img" aria-label="{html.escape(title)}">']
    for r, (name, parts) in enumerate(rows):
        y0 = 2 + r * (bh + gap)
        out.append(f'<text class="tick" x="{lw - 6}" y="{y0 + bh / 2 + 3:.1f}" text-anchor="end">{html.escape(name)}</text>')
        x0 = lw
        for k, v in enumerate(parts):
            w = (W - lw - 8) * v
            if w <= 0:
                continue
            out.append(f'<rect x="{x0:.1f}" y="{y0}" width="{max(w - 2, 1):.1f}" height="{bh}" rx="3" fill="{SERIES[k]}">'
                       f'<title>{html.escape(name)}: {html.escape(labels[k])} {round(v * 100)}%</title></rect>')
            if w > 30:
                out.append(f'<text class="inbar" x="{x0 + 5:.1f}" y="{y0 + bh / 2 + 3.5:.1f}">{round(v * 100)}%</text>')
            x0 += w
    out.append('</svg><div class="legend">')
    for k, lab in enumerate(labels):
        out.append(f'<span><i class="sw" data-c="{k}"></i>{html.escape(lab)}</span>')
    out.append('</div></figure>')
    return ''.join(out)


def charts(root):
    path = os.path.join(root, 'economy', 'report-data.json')
    if not os.path.exists(path):
        return ''
    d = json.load(open(path))
    parts = ['<h3>The lab\'s run in pictures</h3>'
             '<p class="lead">Tap or hover a point for its number. The full tables follow in the report.</p>']

    # 1. Stockpiles of a daily player, in weeks of their own income (one common base).
    ser = []
    for row in d['ledger']['daily']:
        inc = sum(row['inn']) / len(row['inn']) or 1
        ser.append((row['resource'].capitalize(), [s['median'] / inc for s in row['stock']]))
    parts.append(_line_chart('What piles up', 'A daily player\'s stock of each resource, in weeks of its income. Rising lines are things with nothing to spend them on.',
                             ser, 20, [0, 5, 10, 15, 20], lambda v: f'{v:g}'))

    # 2. Creature levels of a daily and a weekly player.
    g = {r['profile']: r for r in d['growth']}
    ser = [('Daily: best', [p['median'] for p in g['daily']['first']]),
           ('Daily: 10th', [p['median'] for p in g['daily']['tenth']]),
           ('Weekly: best', [p['median'] for p in g['weekly']['first']]),
           ('Weekly: 10th', [p['median'] for p in g['weekly']['tenth']])]
    parts.append(_line_chart('How creatures grow', 'Levels of the best and the 10th creature. The level cap is 30.',
                             ser, 30, [0, 10, 20, 30], short=['D best', 'D 10th', 'W best', 'W 10th']))

    # Forge time per kind of player.
    names = {'daily': 'Daily', 'active': '3 a day', 'every-other-day': 'Every 2 days', 'weekend-off': 'Weekend off', 'weekly': 'Weekly', 'returner': 'Returner'}
    fr = {r['profile']: r['share'] for r in d['forge']}
    rows = [(names[k], [fr[k]['work'], fr[k]['shard'], max(0.0, 1 - fr[k]['work'] - fr[k]['shard'])]) for k in names if k in fr]
    parts.append(_split_bars('What the Forge does all day', 'Share of anvil time over 24 weeks, with the shard exchange. Scrap never runs out; the wait is for a shard of the right element.',
                             rows, ['Making pieces', 'Waiting for a shard', 'Other (tinkering, a full floor)']))

    # Kinds owned by rarity (a daily player), and what a server of 8 owns between its players.
    br = g['daily'].get('byRarity')
    if br:
        ser = [(f'{name} owned', [p['median'] for p in br['owned'][k]]) for k, name in enumerate(['Commons', 'Rares', 'Epics'])]
        ser += [('Commons in the game', [p['median'] for p in br['available'][0]])]
        parts.append(_line_chart('How the collection grows', "A daily player's kinds by rarity, against the commons in the game (new species every 4 weeks: an example). Commons come fast, rarer ones slowly.",
                                 ser, 60, [0, 20, 40, 60], short=['Commons', 'Rares', 'Epics', 'In game']))
    cov_path = os.path.join(root, 'economy', 'server-coverage.json')
    if os.path.exists(cov_path):
        cov = json.load(open(cov_path)).get('mixed8', [])
        if cov:
            ser = [(name, [100 * w[key] for w in cov]) for name, key in (('Commons', 'common'), ('Rares', 'rare'), ('Epics', 'epic'))]
            parts.append(_line_chart('What a server of 8 can pool for the raid', 'Share of each rarity\'s species in the game that at least one player owns.',
                                     ser, 100, [0, 25, 50, 75, 100], lambda v: f'{v:g}%', short=['Commons', 'Rares', 'Epics']))

    # 3. Place level-ups on a server of 8 against the plan.
    s8 = next(s for s in d['servers'] if s['id'] == 'mixed8')
    ups = [sum(lv) - 5 for lv in s8['levels']]
    ref = [5.5 * i / 11 if i <= 11 else None for i in range(len(ups))]
    parts.append(_line_chart('How fast the valley builds', 'Level-ups across the five places on a server of 8. The plan said about 5 or 6 by week 12; every place tops out at level 5 (20 level-ups).',
                             [('Server of 8', ups)], 20, [0, 5, 10, 15, 20], ref=('The plan', ref)))

    # 4. The Forge's fire (no time floor since round 16), with the old slow floor for comparison.
    fd = d['fireByDial']
    sf = d.get('fireSlowFloor', {})
    ser = [('All bosses', fd['all']['fire']), ('Half', fd['half']['fire']), ('No bosses', fd['none']['fire'])]
    if 'none' in sf:
        ser.append(('No bosses, old slow floor', sf['none']['fire']))
    parts.append(_line_chart('The Forge\'s fire (the item level cap)', 'On a server of 8, by how many raid bosses it kills. Only building, collections and boss kills warm it (no time floor); the old slow floor would only have helped a server that never wins.',
                             ser, 100, [0, 25, 50, 75, 100], short=['All', 'Half', 'None', 'Old floor']))
    return ''.join(parts)
