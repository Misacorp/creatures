#!/usr/bin/env node
// PostToolUse hook (matcher "Edit|Write|MultiEdit"): after an edit inside docs/design/decisions/, runs
// `pnpm decisions fix` so ids, statuses, order and the README index are always up to date. If fix reports
// problems the agent sees them (decision "block"); if it changed files the agent is told which.
import { execFileSync, spawnSync } from 'node:child_process';
import { basename, dirname, isAbsolute, relative, resolve } from 'node:path';
import process from 'node:process';

try {
  let raw = '';
  for await (const chunk of process.stdin) raw += String(chunk);
  const input = JSON.parse(raw);
  const project = process.env.CLAUDE_PROJECT_DIR || input.cwd;
  const file = input.tool_input?.file_path;
  if (typeof project === 'string' && typeof file === 'string') {
    const abs = resolve(input.cwd ?? project, file);
    // The checkout that holds the file: an agent in a worktree edits its own copy, and fix runs there.
    const root = execFileSync('git', ['rev-parse', '--show-toplevel'], {
      cwd: dirname(abs),
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    const rel = relative(root, abs);
    const inside =
      !isAbsolute(rel) && !rel.startsWith('..') && dirname(rel) === 'docs/design/decisions';
    if (inside && abs.endsWith('.md')) {
      // Fix runs for README.md too, so a hand edit of the generated index is undone at once.
      const result = spawnSync('node', ['scripts/decisions.mjs', 'fix', '--quiet'], {
        cwd: root,
        encoding: 'utf8',
        timeout: 20_000,
      });
      const output = `${result.stdout ?? ''}${result.stderr ?? ''}`.trim();
      if (basename(abs) === 'README.md') {
        console.log(
          JSON.stringify({
            decision: 'block',
            reason:
              'docs/design/decisions/README.md is generated by `pnpm decisions fix` (just run, so it is regenerated). Do not edit it by hand: edit a topic file instead.',
          }),
        );
      } else if (result.status !== 0) {
        console.log(
          JSON.stringify({
            decision: 'block',
            reason: `pnpm decisions fix: ${output || 'failed'}`,
          }),
        );
      } else if (output) {
        console.log(
          JSON.stringify({
            hookSpecificOutput: {
              hookEventName: 'PostToolUse',
              additionalContext: `decisions fix ${output}`,
            },
          }),
        );
      }
    }
  }
} catch {
  // A hook must never break the session.
}
