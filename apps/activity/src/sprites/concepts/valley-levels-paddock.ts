// ---------------------------------------------------------------- level 4: Valley
/** Teal and cream bunting along a sagging line from (xa, ya) to (xb, yb). */
function bunting(g: Grid, xa: number, ya: number, xb: number, yb: number): void {
  const n = Math.abs(xb - xa);
  const dir = xb > xa ? 1 : -1;
  for (let i = 0; i <= n; i++) {
    const t = i / n;
    const y = Math.round(ya + (yb - ya) * t + Math.sin(Math.PI * t) * 3);
    const x = xa + dir * i;
    put(g, x, y, 'k');
    if (i % 3 === 1 && i < n - 1) {
      const c = (i / 3) % 2 === 0 ? 'e' : 'c';
      stamp(g, x, y + 1, [`${c}${c}`, `${c}k`.replace('k', c)]);
      put(g, x, y + 3, 'k');
    }
  }
}
