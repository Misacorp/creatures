// ---------------------------------------------------------------- shared by levels 3 to 5
interface Barn {
  readonly wall: string; // wall fill
  readonly wallShade: string;
  readonly beam: Kit;
  readonly door: Kit;
  readonly trim: string | undefined; // eave trim
  readonly roofLit?: string; // the light rib of the barrel tiles (`r`; a level out of colours uses `a`)
  readonly stoneHi?: string;
}

/** The barn: a slate roof (rows 5..13) over a wall (14..19), door in the middle. */
function barn(g: Grid, b: Barn, stoneBase: boolean): void {
  roof(g, 32, 5, 6, 4, 2, 'a', 'A', b.trim, b.roofLit ?? 'r', true);
  // wall
  for (let y = 12; y <= 19; y++) {
    for (let x = 18; x <= 45; x++) {
      let ch = b.wall;
      if (y === 12) ch = b.beam.lo;
      else if ((x + y) % 5 === 0 && y % 2 === 0) ch = b.wallShade;
      put(g, x, y, ch);
    }
  }
  run(g, 12, 18, 45, 'k');
  run(g, 13, 18, 45, b.beam.hi);
  if (stoneBase) stoneWall(g, 18, 45, 17, 19, b.stoneHi);
  // timber posts at the ends and either side of the door
  for (const x of [18, 44]) for (let y = 12; y <= 19; y++) stamp(g, x, y, ['k' + b.beam.hi]);
  for (const x of [19, 45]) for (let y = 12; y <= 19; y++) put(g, x, y, 'k');
  // the door: a plank leaf with iron straps
  rect(g, 28, 14, 35, 19, 'k');
  for (let y = 15; y <= 19; y++) {
    for (let x = 29; x <= 34; x++) put(g, x, y, (x - 29) % 2 === 0 ? b.door.hi : b.door.lo);
  }
  put(g, 31, 14, b.door.hi);
  put(g, 32, 14, b.door.hi);
}
