/**
 * The Paddock at the five valley levels (docs/design/art-levels.md), concept art (not in the game).
 * All five are 64x64 on one footprint: side fences at x 3..7 and 56..60, a back fence at rows 20..23, a
 * front fence at rows 42..50 with the gate gap at x 28..37; the fence changes material, never place. The
 * barn grows on the rows above the back fence (rows 0..19). Creatures roam in `PADDOCK_ROAM`, which is
 * open ground (grass or the lantern's light on it) at every level.
 *
 * Night is the main palette with the lantern's light on the grass; `alts.day` recolours the same pixels.
 * Materials come from `TIERS` (valley-tiers.ts) so a level's shingles, stone and paint match its
 * neighbours across the valley. Generated by a script from shapes, then kept as data.
 */
import type { SpriteDef } from '../sprite-data';
import { VALLEY_GLOW_CONCEPTS } from './valley-glow';
import { INK, tierPalette, TIERS, type Shade } from './valley-tiers';
import type { ConceptSet } from './index';

/** Where creatures roam, in sprite pixels: the same rectangle at every level, open ground only. */
export const PADDOCK_ROAM = { x: 15, y: 24, width: 34, height: 17 } as const;

const W = 64;
const H = 64;
type Grid = string[][];

const blank = (): Grid => Array.from({ length: H }, () => Array<string>(W).fill('.'));
const toRows = (g: Grid): string[] => g.map((r) => r.join(''));

function put(g: Grid, x: number, y: number, ch: string): void {
  if (x >= 0 && x < W && y >= 0 && y < H) (g[y] as string[])[x] = ch;
}
function run(g: Grid, y: number, x0: number, x1: number, ch: string): void {
  for (let x = x0; x <= x1; x++) put(g, x, y, ch);
}
function rect(g: Grid, x0: number, y0: number, x1: number, y1: number, ch: string): void {
  for (let y = y0; y <= y1; y++) run(g, y, x0, x1, ch);
}
/** Stamp a piece with its top-left at (x, y); a space leaves the pixel as it is. */
function stamp(g: Grid, x: number, y: number, piece: readonly string[]): void {
  piece.forEach((line, dy) => {
    [...line].forEach((ch, dx) => {
      if (ch !== ' ') put(g, x + dx, y + dy, ch);
    });
  });
}

/** The keys a level uses for its wood-like fence parts. */
interface Kit {
  readonly hi: string;
  readonly lo: string;
  /** Post and rail ends: a cap colour (defaults to `lo`). */
  readonly cap?: string;
}

/** A horizontal rail, 4 rows: ink, light, dark, ink. `nails` puts a dot on its light row. */
function rail(g: Grid, x0: number, x1: number, y: number, kit: Kit, nail?: string): void {
  run(g, y, x0, x1, 'k');
  run(g, y + 1, x0, x1, kit.hi);
  run(g, y + 2, x0, x1, kit.lo);
  run(g, y + 3, x0, x1, 'k');
  if (nail !== undefined) for (let x = x0 + 5; x < x1; x += 11) put(g, x, y + 1, nail);
}
/** A post, 4 wide, ink all round, with a cap row on top. */
function post(g: Grid, x: number, y0: number, y1: number, kit: Kit): void {
  for (let y = y0; y <= y1; y++) {
    put(g, x, y, 'k');
    put(g, x + 1, y, kit.hi);
    put(g, x + 2, y, kit.lo);
    put(g, x + 3, y, 'k');
  }
  run(g, y0, x, x + 3, 'k');
  if (kit.cap !== undefined) run(g, y0 + 1, x + 1, x + 2, kit.cap);
}
/** A side fence seen end-on: a column 5 wide with an ink seam every 6 rows. */
function sideColumn(g: Grid, x: number, y0: number, y1: number, kit: Kit): void {
  for (let y = y0; y <= y1; y++) {
    const seam = (y - y0) % 6 === 5 || y === y0 || y === y1;
    if (seam) run(g, y, x, x + 4, 'k');
    else {
      put(g, x, y, 'k');
      put(g, x + 1, y, kit.hi);
      put(g, x + 2, y, kit.lo);
      put(g, x + 3, y, kit.lo);
      put(g, x + 4, y, 'k');
    }
  }
}
/** A dressed-stone course: rows of blocks with ink between, over [x0..x1] and [y0..y1]. */
function stoneWall(g: Grid, x0: number, x1: number, y0: number, y1: number, hi = 'L'): void {
  for (let y = y0; y <= y1; y++) {
    const course = (y - y0) % 4;
    for (let x = x0; x <= x1; x++) {
      const joint = (x - x0 + (Math.floor((y - y0) / 4) % 2) * 3) % 6 === 5;
      let ch = course === 0 ? hi : course === 3 ? 'T' : 't';
      if (joint && course !== 0) ch = 'k';
      put(g, x, y, ch);
    }
  }
  run(g, y1, x0, x1, 'k');
}

/**
 * A shingle or tile roof: stepped trapezoid, ink all round, a darker tick pattern. With `lit` the roof has
 * one light from the upper left like the walls: left of the centre line is the lit plane (`lit` as the body,
 * `main` as the ticks), right of it the shaded plane (`main` body, `shade` ticks). `barrel` draws terracotta
 * barrel tiles instead: ribs of `lit`, `main` and `shade`, courses offset by two.
 */
function roof(
  g: Grid,
  cx: number,
  y0: number,
  rows: number,
  half0: number,
  step: number,
  main: string,
  shade: string,
  trim?: string,
  lit?: string,
  barrel = false,
): void {
  for (let i = 0; i < rows; i++) {
    const a = cx - half0 - step * i;
    const b = cx + half0 - 1 + step * i;
    const y = y0 + i;
    if (lit === undefined) {
      run(g, y, a, b, main);
      for (let x = a + 1 + ((i * 2) % 4); x < b; x += 4) put(g, x, y, shade);
    } else if (barrel) {
      for (let x = a; x <= b; x++) put(g, x, y, [lit, main, main, shade][(x + i * 2) % 4]!);
    } else {
      for (let x = a; x <= b; x++) {
        const tick = (x - a - 1 - ((i * 2) % 4)) % 4 === 0 && x > a;
        put(g, x, y, x < cx ? (tick ? main : lit) : tick ? shade : main);
      }
    }
    put(g, a, y, 'k');
    put(g, b, y, 'k');
    if (i === 0) run(g, y, a, b, 'k');
  }
  const a = cx - half0 - step * (rows - 1) - 1;
  const b = cx + half0 - 1 + step * (rows - 1) + 1;
  run(g, y0 + rows, a, b, 'k');
  if (trim !== undefined) run(g, y0 + rows - 1, a + 1, b - 1, trim);
}

/** Hay heap, 11x7, standing on the back fence at the left. */
function hay(g: Grid, s: string, d: string): void {
  stamp(
    g,
    9,
    17,
    [
      '....kkk....',
      '..kkssskk..',
      `.ks${s}sssd${d}k.`.replace(`${d}${d}`, d),
      `ksssss${s}sdk`.padEnd(11, 'k'),
      `ks${s}sssssdk`,
      `k${d}sssss${s}${d}${d}k`,
      'kkkkkkkkkkk',
    ].map((r) => r.replaceAll('s', s).replaceAll('d', d)),
  );
}

/** The lantern: 3x5; `cap` colours its top and base, `glass` its light. */
function lantern(g: Grid, x: number, y: number, cap: string, glass: string): void {
  stamp(g, x, y, [' k ', `${cap}${cap}${cap}`, `k${glass}k`, `k${glass}k`, `${cap}${cap}${cap}`]);
}

/** Stepped light on the ground round a lantern: `3` at the core, `2`, a `2`/`1` check, dithered `1` outside. */
function groundLight(g: Grid, cx: number, cy: number, scale = 1): void {
  const rx = 21 * scale;
  const ry = 8 * scale;
  for (let y = Math.floor(cy - ry); y <= Math.ceil(cy + ry); y++) {
    for (let x = Math.floor(cx - rx); x <= Math.ceil(cx + rx); x++) {
      if (g[y]?.[x] !== '.') continue;
      const d = ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2;
      if (d <= 0.08) put(g, x, y, '3');
      else if (d <= 0.25) put(g, x, y, '2');
      else if (d <= 0.5) put(g, x, y, (x + y) % 2 === 0 ? '2' : '1');
      else if (d <= 0.78 && (x + y) % 2 === 0) put(g, x, y, '1');
      else if (d <= 1 && x % 2 === 0 && y % 2 === 0) put(g, x, y, '1');
    }
  }
}

/** The cast shadow under the front fence and side columns. */
function shadows(g: Grid, spans: readonly (readonly [number, number])[]): void {
  for (const [a, b] of spans) run(g, 51, a, b, 'x');
}

// Own colours (night, day): the light spill, the shadow, the water, lamp glass.
const OWN: Readonly<Record<string, Shade>> = {
  k: { night: INK, day: INK },
  x: { night: '#112430', day: '#2f5a38' },
  '1': { night: '#55703f', day: '#467a4c' },
  '2': { night: '#8a8a40', day: '#8e8a4c' },
  '3': { night: '#d09a3c', day: '#8a6a48' },
  z: { night: '#3a6a98', day: '#4a8ac0' },
  G: { night: '#ffd966', day: '#a8b8b0' },
  H: { night: '#fff6c8', day: '#dce8e4' },
  f: { night: '#d0587a', day: '#e0608a' },
};

type Parts = { palette: Record<string, string>; day: Record<string, string> };

function build(parts: readonly Parts[], own: readonly string[], g: Grid): LevelOut {
  const palette: Record<string, string> = {};
  const day: Record<string, string> = {};
  for (const p of parts) {
    Object.assign(palette, p.palette);
    Object.assign(day, p.day);
  }
  for (const key of own) {
    const s = OWN[key] as Shade;
    palette[key] = s.night;
    day[key] = s.day;
  }
  const rows = toRows(g);
  const used = new Set(rows.join(''));
  const keep = (m: Record<string, string>): Record<string, string> =>
    Object.fromEntries(Object.entries(m).filter(([k]) => used.has(k)));
  return { sprite: { palette: keep(palette), rows }, alts: { day: keep(day) } };
}
interface LevelOut {
  sprite: SpriteDef;
  alts: { day: Record<string, string> };
}

const LEFT_RAIL: readonly [number, number] = [3, 23];
const RIGHT_RAIL: readonly [number, number] = [42, 60];

// ---------------------------------------------------------------- level 1: Humble
function level1(): LevelOut {
  const g = blank();
  const L = { hi: 'l', lo: 'L' };
  // Back: stakes with a rope. Front: stakes with two ropes, each side of the gap. Sides: stakes down a column.
  const stakesRow = (x0: number, x1: number, top: number, bottom: number, rows: number[]): void => {
    for (const ry of rows) run(g, ry, x0, x1, 'r');
    let i = 0;
    for (let x = x0; x + 2 <= x1; x += 5, i++) {
      const t = top + ((i * 5) % 3);
      for (let y = t; y <= bottom; y++) stamp(g, x, y, y === t ? [' k '] : ['kLk']);
      for (let y = t + 1; y <= bottom; y++) put(g, x + 1, y, 'l');
      put(g, x + 1, t, 'k');
      // the rope's ink under it
      for (const ry of rows) if (ry + 1 <= bottom) put(g, x + 1, ry + 1, 'k');
    }
    for (const ry of rows)
      for (let x = x0; x <= x1; x++) if (g[ry + 1]?.[x] === '.') put(g, x, ry + 1, 'k');
  };
  stakesRow(8, 55, 18, 23, [20]);
  stakesRow(LEFT_RAIL[0], 25, 42, 50, [45, 48]);
  stakesRow(RIGHT_RAIL[0] - 2, RIGHT_RAIL[1], 42, 50, [45, 48]);
  // the side columns: a stake every 6 rows, rope running down between
  for (const x of [3, 56]) {
    for (let y = 18; y <= 49; y++) {
      if ((y - 18) % 6 === 5 || y === 49) continue;
      put(g, x + 2 + ((y * 7) % 5 === 0 ? 1 : 0), y, 'r');
    }
    for (let y = 18, i = 0; y <= 46; y += 6, i++) {
      const dx = (i % 3) - 1;
      stamp(g, x + 1 + dx, y, ['kkk', 'klk', 'klL', 'kLL', 'kLk', 'kkk']);
      put(g, x + 1 + dx + 1, y + 1, 'l');
    }
  }
  // a taller stake at the front right, with the lantern on a branch
  for (let y = 38; y <= 50; y++) stamp(g, 57, y, y === 38 ? [' k '] : ['klk']);
  for (let y = 40; y <= 50; y++) put(g, 58, y, y % 3 === 0 ? 'L' : 'l');
  run(g, 39, 54, 56, 'k');
  lantern(g, 53, 39, 'k', 'G');
  // the gate: two bigger stakes with a rope tied aside, loose fieldstones, a hay heap, a bucket
  for (const x of [26, 39])
    for (let y = 41; y <= 50; y++) stamp(g, x, y, y === 41 ? [' k '] : ['kLk']);
  for (const x of [26, 39]) for (let y = 42; y <= 50; y++) put(g, x + 1, y, 'l');
  stamp(g, 11, 45, ['kffk', 'kffk']);
  stamp(g, 10, 36, ['kfk']);
  stamp(g, 47, 47, ['kfk']);
  hay(g, 's', 'e');
  stamp(g, 49, 17, [' kkkk ', 'kzzzzk', 'klLllk', 'klLllk', 'krrrrk', 'klLllk', ' kkkk ']);
  stamp(g, 48, 16, ['k    k']); // the rope handle
  run(g, 15, 49, 54, 'k');
  shadows(g, [
    [3, 8],
    [LEFT_RAIL[0], 25],
    [27, 28],
    [40, 41],
    [42, 60],
  ]);
  groundLight(g, 47, 54, 0.8);
  const t1 = tierPalette(1, {
    l: 'log',
    L: 'logShade',
    r: 'rope',
    s: 'straw',
    e: 'earth',
    f: 'fieldstone',
  });
  void L;
  return build([t1], ['k', 'x', '1', '2', '3', 'z', 'G'], g);
}

