/**
 * House furniture pack: Moonlit (Night-reef blue lacquer with a crescent inlay, coral pink trim, a moonstone knob and silver rims.).
 * Nine pieces, a wallpaper, a floor and a keepsake, all in one palette. `.` transparent, `k` the ink outline
 * shared with the creature and room sprites; the wallpaper and floor tiles have no outline. Light comes from the
 * top left. Keys `s` and `t` are the window's sky and cloud, `y` and `z` the lamp's night glow.
 * Piece ids are `<set>-<form>`, sizes fit the form boxes of `docs/design/housing.md` 2.5. The bed's `sleep` is the
 * top left of the 16x16 sleeper in the bed's own pixels; its `front` (the blanket) is drawn over the sleeper.
 */
import type { SpriteDef } from '../../sprite-data';

// Declared here until the house scene's `house-art.ts` defines them; then import them from there.
interface PieceArt {
  sprite: SpriteDef;
  front?: SpriteDef;
  sleep?: { x: number; y: number };
  glow?: SpriteDef;
}
interface HouseArtPack {
  pieces?: Record<string, PieceArt>;
  skins?: Record<string, { tile: SpriteDef; ridge?: SpriteDef; eave?: SpriteDef }>;
  keepsakes?: Record<string, SpriteDef>;
}

const PALETTE: Readonly<Record<string, string>> = {
  k: '#0d0a1a',
  a: '#98acf0',
  b: '#6c84d4',
  c: '#4a5eac',
  d: '#f59bb0',
  e: '#c8607f',
  g: '#cfd6f0',
  h: '#f7f9ff',
  i: '#a493e6',
  j: '#7061bb',
  m: '#c8eefa',
  n: '#84bfdc',
  w: '#2c3a80',
  v: '#3a4c98',
  s: '#8ccaf2',
  t: '#e2f2fb',
  y: '#eaf5ff',
  z: '#a9c9f2',
};

/** A sprite with only the palette keys its rows use. */
function art(rows: readonly string[]): SpriteDef {
  const used = new Set(rows.join(''));
  return {
    rows,
    palette: Object.fromEntries(Object.entries(PALETTE).filter(([key]) => used.has(key))),
  };
}

