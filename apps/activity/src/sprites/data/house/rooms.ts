/**
 * Room skins (housing art pass 2): a default wallpaper (16x52) and floor (16x8) for every indoor room kind except
 * the Hearth, Loft and Study, which stay on Cosy, so the parts of a big house read as different rooms of one house.
 * Each pair has its own palette (two to four colours plus shades) and no outline; they tile sideways without seams.
 * Ids are `<room>-wall` and `<room>-floor`. They are free: they come with the part that has the room.
 *
 * Kitchen: cream plaster over a terracotta backsplash, terracotta and cream floor. Attic: bare boards between a rafter,
 * dusty floor. Cellar: damp stone blocks, flagstones. Trophy Hall: dark panelling with brass, parquet. Gallery: pale
 * plaster with a gold picture rail, chevron oak. Conservatory: panes of sky in thin frames, diamond tiles. Bath: white
 * tiles with a teal band, mosaic floor. Guest Room: sage pinstripes, cream beadboard, whitewashed planks.
 * (Generated once from shapes, then kept as data.)
 */
