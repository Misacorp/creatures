/** A tile with only the palette keys its rows use. */
const tile = (rows: readonly string[], palette: Readonly<Record<string, string>>): SpriteDef => ({
  rows,
  palette: Object.fromEntries(
    Object.entries(palette).filter(([key]) => rows.some((row) => row.includes(key))),
  ),
});

