/**
 * Lantern Night furniture set (housing art batch E3): paper lanterns and bunting on painted wood.
 * One palette for every piece and skin of the set; the motif on each piece: red lacquer with hanging bunting flags and gold tassels.
 * Pieces stand on their bottom row and fit their form's box (`docs/design/housing.md` 2.5).
 */
import type { SpriteDef } from '../../sprite-data';

export interface PieceArt {
  sprite: SpriteDef;
  front?: SpriteDef;
  sleep?: { x: number; y: number };
  glow?: SpriteDef;
}
export interface HouseArtPack {
  pieces?: Record<string, PieceArt>;
  skins?: Record<string, { tile: SpriteDef; ridge?: SpriteDef; eave?: SpriteDef }>;
  keepsakes?: Record<string, SpriteDef>;
}

const PALETTE: Readonly<Record<string, string>> = {
  k: '#0d0a1a',
  a: '#cf3a3a',
  b: '#f06a58',
  c: '#8e2437',
  d: '#f4c24a',
  e: '#b9852a',
  f: '#f7edd2',
  g: '#d6c49a',
  h: '#5c2b3a',
  i: '#6a9fd8',
};

/** A sprite with only the palette keys its rows use. */
const sprite = (rows: readonly string[]): SpriteDef => ({
  rows,
  palette: Object.fromEntries(
    Object.entries(PALETTE).filter(([key]) => rows.some((row) => row.includes(key))),
  ),
});

