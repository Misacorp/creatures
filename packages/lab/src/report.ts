/**
 * The lab report: scenarios from the design library, the best-team search per rule card, and a
 * raid weekend with attrition. Written to docs/design/combat/lab-report.md by `pnpm --filter @creatures/lab report`.
 */
import { createSeededRng } from '@creatures/game';
import { CARDS, labBoss } from './cards';
import { weekend } from './fight';
import { FORM_KNACKS, KNACKS } from './knacks';
import { LAB_RULES } from './rules';
import {
  GAUNTLET,
  POOL,
  RAID,
  bossFor,
  classicFor,
  evaluate,
  search,
  toPlacements,
  type Mode,
  type Pick,
  type Ranked,
} from './search';

const P = (s: string): Pick => {
  const [formId, knack] = s.split('/');
  return { formId: formId ?? '', knack: knack ?? '' };
};
const line = (s: string) => s.split(' ').map(P);

export const SCENARIOS: Readonly<Record<string, string>> = {
  'Classic: Tidewing, Tempestray Detonate, Thornbuck':
    'tidewing/soak-through tempestray/detonate thornbuck/wide-reach',
  'Two Setters into Detonate': 'splashet/lead-the-way tidewing/soak-through tempestray/detonate',
  'Downpour into Detonate': 'tidewing/downpour tempestray/detonate thornbuck/wide-reach',
  'Overcharge into a Grove Detonate': 'voltaro/overcharge bloomback/detonate thornbuck/wide-reach',
  'Chain: Overload leaves Charged for Bloomback':
    'tidewing/soak-through tempestray/leave-a-trail bloomback/detonate',
  'No Setter: Ready the Mark feeds Geyserpup':
    'kilnmole/draw-fire geyserpup/leave-a-trail magmole/ready-the-mark',
  'No Setter: Own Puddle': 'kilnmole/draw-fire geyserpup/own-puddle magmole/tunnel-through',
  'Big Spout on stacked Scorched':
    'magmole/ready-the-mark geyserpup/big-spout kilnmole/baked-shell',
  'Twin Strike': 'tidewing/soak-through tempestray/twin-strike thornbuck/wide-reach',
  'Dodge tank: Zigzag beside a Guard': 'voltaro/zigzag ohmouse/catch-the-bolts tempestray/detonate',
  'Mire: Mud Wall and Squelch Song':
    'bogwarden/mud-wall tempestray/detonate croakmire/squelch-song',
  'No reactions: plain hitters': 'tempestray/twin-strike magmole/tunnel-through kilnmole/draw-fire',
};

export interface Report {
  readonly markdown: string;
  readonly data: unknown;
}

const r0 = (n: number) => Math.round(n);
const pct = (v: number, base: number) =>
  base ? `${v >= base ? '+' : ''}${Math.round((v / base - 1) * 100)}%` : 'n/a';
const name = (p: Pick) => `${p.formId} (${KNACKS[p.knack]?.name ?? p.knack})`;

export function buildReport(opts: { quick?: boolean } = {}): Report {
  const seeds = opts.quick ? 4 : 12;
  const sopts = opts.quick
    ? { starts: 60, keep: 10, rounds: 2, seeds: 3 }
    : { starts: 400, keep: 40, rounds: 4, seeds: 6 };
  const ropts = opts.quick
    ? { starts: 30, keep: 6, rounds: 1, seeds: 2 }
    : { starts: 160, keep: 16, rounds: 3, seeds: 3 };
  const md: string[] = [];
  const data: Record<string, unknown> = {};
  md.push('# Combat v2 lab report', '');
  md.push(
    `Generated by \`pnpm --filter @creatures/lab report${opts.quick ? ' -- --quick' : ''}\`. A prototype of the draft rules (\`packages/lab\`), not the shipped engine. Level ${25} creatures, a neutral boss with huge HP (damage over 10 rounds; a wipe ends the fight early). Knobs: Payoff x${LAB_RULES.payoffMultBp / 10_000}, extra stack +${LAB_RULES.extraStackBp / 100}% bonus, Guard armour ${LAB_RULES.armourByRole.guard}, boss armour 20.`,
    '',
  );

  // 1. Scenarios, gauntlet (one row of three).
  const cards = CARDS.filter((c) => c.id !== 'adapts');
  md.push(
    '## Scenarios (gauntlet: one row of three)',
    '',
    'Mean damage over ' +
      seeds +
      ' seeds. Percent is against the classic line on the same card. KO is knockouts per fight.',
    '',
  );
  md.push(
    `| Line | ${cards.map((c) => c.name).join(' | ')} |`,
    `| --- | ${cards.map(() => '---:').join(' | ')} |`,
  );
  const scen: Record<string, Record<string, unknown>> = {};
  const base: Record<string, number> = {};
  for (const [label, spec] of Object.entries(SCENARIOS)) {
    const cells: string[] = [];
    scen[label] = {};
    for (const c of cards) {
      const s = evaluate(bossFor(GAUNTLET, [c.id]), line(spec), GAUNTLET, seeds, `scen:${c.id}`);
      if (label.startsWith('Classic')) base[c.id] = s.damage;
      cells.push(
        label.startsWith('Classic')
          ? `${r0(s.damage)} (KO ${s.knockouts.toFixed(1)})`
          : `${pct(s.damage, base[c.id] ?? 0)} (KO ${s.knockouts.toFixed(1)})`,
      );
      scen[label][c.id] = { damage: r0(s.damage), ko: s.knockouts };
    }
    md.push(`| ${label} | ${cells.join(' | ')} |`);
  }
  data['scenarios'] = scen;
  md.push('');

  // 2. Best-team search per card, gauntlet and raid.
  const appear = new Map<string, number>(POOL.map((p) => [p.knack, 0]));
  const top5 = (rank: Ranked[]) => rank.slice(0, 5);
  let classicBeaten = 0;
  const perCard: Record<string, unknown> = {};
  for (const mode of [GAUNTLET, RAID] as Mode[]) {
    md.push(
      `## Best teams per card: ${mode.id === 'gauntlet' ? 'gauntlet (one row of three)' : 'raid (3 rows x 4, four players)'}`,
      '',
    );
    md.push(
      '| Card | Best line | Damage | Classic | Classic vs best |',
      '| --- | --- | ---: | ---: | ---: |',
    );
    for (const c of cards) {
      const boss = bossFor(mode, [c.id]);
      const ranked = search(boss, mode, {
        seed: `${mode.id}:${c.id}`,
        ...(mode.id === 'raid' ? ropts : sopts),
      });
      const best = ranked[0];
      const classic = ranked.find((r) =>
        r.line.every(
          (p, i) =>
            p.formId === classicFor(mode)[i]?.formId && p.knack === classicFor(mode)[i]?.knack,
        ),
      );
      if (!best || !classic) continue;
      if (mode.id === 'gauntlet' && classic.score.damage < best.score.damage * 0.9) classicBeaten++;
      for (const r of top5(ranked))
        for (const k of new Set(r.line.map((p) => p.knack)))
          appear.set(k, (appear.get(k) ?? 0) + 1);
      const shown = mode.id === 'gauntlet' ? best.line.map(name).join(', ') : summarise(best.line);
      md.push(
        `| ${c.name} | ${shown} | ${r0(best.score.damage)} | ${r0(classic.score.damage)} | ${pct(classic.score.damage, best.score.damage)} |`,
      );
      perCard[`${mode.id}:${c.id}`] = {
        best: best.line,
        damage: r0(best.score.damage),
        classic: r0(classic.score.damage),
      };
    }
    md.push('');
  }
  data['perCard'] = perCard;
  md.push(
    `**The classic line is more than 10% behind the best gauntlet line on ${classicBeaten} of ${cards.length} cards.** (Target from the player-experience review: at least half.)`,
    '',
  );

  // 3. Knack usage across the top 5 of every search.
  const total = cards.length * 2 * 5;
  const rows = [...appear.entries()].sort((a, b) => b[1] - a[1]);
  md.push(
    '## Knack usage in the top 5 teams of every search',
    '',
    `Out of ${total} top teams (${cards.length} cards, gauntlet and raid, top 5 each). Never used: candidates to rework. Used almost everywhere: candidates for a counter card.`,
    '',
  );
  md.push('| Knack | Forms | Top teams |', '| --- | --- | ---: |');
  for (const [k, n] of rows)
    md.push(
      `| ${KNACKS[k]?.name ?? k} | ${Object.entries(FORM_KNACKS)
        .filter(([, ks]) => ks.includes(k))
        .map(([f]) => f)
        .join(', ')} | ${n} |`,
    );
  data['knackUsage'] = Object.fromEntries(rows);
  md.push('');

  // 4. A raid weekend with attrition.
  md.push(
    '## Raid weekend with attrition (3 stages of 8 rounds, HP carries, knocked-out creatures stay out)',
    '',
  );
  md.push(
    '| Boss | Party | Won | Replacements | Knockouts per stage |',
    '| --- | --- | ---: | ---: | --- |',
  );
  const party = classicFor(RAID);
  const bench = [0, 1, 2, 3].map((i) => ({
    owner: `p${i + 1}`,
    formId: 'kilnmole',
    level: 25,
    knack: 'draw-fire',
    row: 0,
    col: 0,
  }));
  for (const c of ['plain', 'payoff-hunter', 'crusher', 'wither']) {
    let wins = 0,
      reps = 0;
    const kos: number[][] = [];
    const n = opts.quick ? 3 : 10;
    for (let i = 0; i < n; i++) {
      const boss = labBoss({ rows: 3, cols: 4, cards: [c], hp: 30_000, atk: 120, rounds: 8 });
      const w = weekend(boss, toPlacements(party, RAID), bench, {
        rng: createSeededRng(`weekend:${c}:${i}`),
      });
      if (w.won) wins++;
      reps += w.replacements;
      kos.push(w.stages.map((s) => s.knockouts));
    }
    const avg = [0, 1, 2]
      .map((st) => (kos.reduce((a, k) => a + (k[st] ?? 0), 0) / n).toFixed(1))
      .join(' / ');
    md.push(
      `| ${c} | four classic trios, a Kilnmole each on the bench | ${wins} / ${n} | ${(reps / n).toFixed(1)} | ${avg} |`,
    );
  }
  md.push(
    '',
    '## What this cannot tell',
    '',
    '- It is a prototype: talents, gear, crits on heals and boss charges announced on screen are simplified or missing.',
    '- Searches are random plus local improvement; a missing team is not proof that it is weak.',
    '- Fun is not in the numbers. Use this to find outliers and dead options, then test feel in the game.',
    '',
  );
  return { markdown: md.join('\n'), data };
}

/** The Knack catalogue, generated from the data so the text never drifts from what the lab runs. */
export function buildCatalogue(): string {
  const md: string[] = [
    '# Knack catalogue (generated)',
    '',
    'Generated from `packages/lab/src/knacks.ts` by `pnpm --filter @creatures/lab report`. Do not edit by hand: change the data and regenerate. Keywords in braces are defined in `keywords.md`.',
    '',
  ];
  const byForm = Object.entries(FORM_KNACKS);
  md.push('## By form', '', '| Form | Knacks (first is the default) |', '| --- | --- |');
  for (const [form, ks] of byForm)
    md.push(`| ${form} | ${ks.map((k) => KNACKS[k]?.name ?? k).join(', ')} |`);
  md.push('', '## Knacks', '');
  for (const k of Object.values(KNACKS)) {
    const forms = byForm
      .filter(([, ks]) => ks.includes(k.id))
      .map(([f]) => f)
      .join(', ');
    md.push(
      `### ${k.name}`,
      '',
      `- **Text:** ${k.text}`,
      `- **Family:** ${k.family}`,
      `- **Forms:** ${forms || 'none yet'}`,
      `- **Intent (for contributors, never shown to players):** ${k.intent}`,
      '',
    );
  }
  return md.join('\n');
}

/** A raid line in short: counts of form (Knack). */
function summarise(l: readonly Pick[]): string {
  const n = new Map<string, number>();
  for (const p of l) n.set(name(p), (n.get(name(p)) ?? 0) + 1);
  return [...n.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([k, c]) => `${c}x ${k}`)
    .join(', ');
}
