/**
 * The effect vocabulary of combat v2 as data: what a Knack's or a talent's `fx` may hold. The same shape as the engine's
 * `KnackFx` (`packages/engine/src/v2/effects.ts`, where every field is documented): the game cannot import the engine (the
 * engine depends on the game), so each side has its own copy and a type test in the engine
 * (`packages/engine/test/v2-content-types.test.ts`) fails the typecheck when they drift. A new effect field is added to both.
 *
 * Numbers are whole numbers, basis points (bp) where the name says so: 10000 is 100%.
 */
import * as v from 'valibot';

const Int = v.pipe(v.number(), v.integer());

/** One Knack's or talent's effects: strict, every field optional. */
export const FxSchema = v.pipe(
  v.strictObject({
    reachBonus: v.exactOptional(Int),
    taunt: v.exactOptional(v.boolean()),
    armourBonus: v.exactOptional(Int),
    dodgeBonusBp: v.exactOptional(Int),
    noDamage: v.exactOptional(v.boolean()),
    plainBp: v.exactOptional(Int),
    twinStrikeBp: v.exactOptional(Int),
    markStacks: v.exactOptional(Int),
    markOthers: v.exactOptional(v.boolean()),
    marksAs: v.exactOptional(v.picklist(['own', 'cashable'])),
    seal: v.exactOptional(v.boolean()),
    leadBoostBp: v.exactOptional(Int),
    spendAllBp: v.exactOptional(Int),
    bonusBp: v.exactOptional(Int),
    minStacks: v.exactOptional(Int),
    trail: v.exactOptional(v.boolean()),
    healOnReactionBp: v.exactOptional(Int),
    retaliateBp: v.exactOptional(Int),
    storeDodgeStacks: v.exactOptional(Int),
    noIntercept: v.exactOptional(v.boolean()),
    interceptArea: v.exactOptional(v.boolean()),
    watchCutBp: v.exactOptional(Int),
    interceptCharged: v.exactOptional(v.boolean()),
    primeOnIntercept: v.exactOptional(v.boolean()),
    rowAreaCutBp: v.exactOptional(Int),
    bakedShell: v.exactOptional(v.boolean()),
    pierceBesideBp: v.exactOptional(Int),
    pierceOwnBp: v.exactOptional(Int),
    support: v.exactOptional(
      v.picklist([
        'wideWarmth',
        'sunbeam',
        'curlUp',
        'readyMark',
        'clearSkies',
        'clearAir',
        'gatherCalm',
        'rowRain',
        'rowBoost',
      ]),
    ),
    besideDodgeBp: v.exactOptional(Int),
    rowDodgeBp: v.exactOptional(Int),
    besideGuardBp: v.exactOptional(Int),
    alonePayoffBp: v.exactOptional(Int),
    besideAreaCutBp: v.exactOptional(Int),
    interceptLikeGuard: v.exactOptional(v.boolean()),
    besideNoSilence: v.exactOptional(v.boolean()),
    guardMendBp: v.exactOptional(Int),
    atkBp: v.exactOptional(Int),
    critChanceBp: v.exactOptional(Int),
    reactionCritBp: v.exactOptional(Int),
    firstHitBp: v.exactOptional(Int),
    secondWindBp: v.exactOptional(Int),
    hpBp: v.exactOptional(Int),
    critDamageBp: v.exactOptional(Int),
    dodgeCritBp: v.exactOptional(Int),
    guardCritBp: v.exactOptional(Int),
    critWardBp: v.exactOptional(Int),
    lowHpAtkBp: v.exactOptional(Int),
    areaCutBp: v.exactOptional(Int),
    holdOn: v.exactOptional(v.boolean()),
    reactionBonusBp: v.exactOptional(Int),
    areaDodgeBp: v.exactOptional(Int),
    ignoreSilence: v.exactOptional(v.boolean()),
    coverBonusBp: v.exactOptional(Int),
    boostBonusBp: v.exactOptional(Int),
    mendBonusBp: v.exactOptional(Int),
    healReceivedBp: v.exactOptional(Int),
    miresOnHit: v.exactOptional(v.boolean()),
    miresAtStart: v.exactOptional(v.boolean()),
    perKindredBesideBp: v.exactOptional(Int),
    oddOneOutBp: v.exactOptional(Int),
    rowEndBp: v.exactOptional(Int),
    frontCutBp: v.exactOptional(Int),
    slowBurnBp: v.exactOptional(Int),
    slowBurnCapBp: v.exactOptional(Int),
    finisherBp: v.exactOptional(Int),
    steadyRhythm: v.exactOptional(v.boolean()),
    cashHighBp: v.exactOptional(Int),
    freshMarkBp: v.exactOptional(Int),
    ownMarkBp: v.exactOptional(Int),
    firstMarkExtra: v.exactOptional(Int),
    vengefulBp: v.exactOptional(Int),
    momentumBp: v.exactOptional(Int),
    flankGuard: v.exactOptional(v.boolean()),
    distanceCoverBp: v.exactOptional(Int),
    interceptHitBackBp: v.exactOptional(Int),
    braceBp: v.exactOptional(Int),
    miredExtraBp: v.exactOptional(Int),
    clinging: v.exactOptional(v.boolean()),
    brightBoost: v.exactOptional(v.boolean()),
    kindredBoostBp: v.exactOptional(Int),
    triageBp: v.exactOptional(Int),
    spillOver: v.exactOptional(v.boolean()),
    cullBp: v.exactOptional(Int),
  }),
  v.readonly(),
);
export type Fx = v.InferOutput<typeof FxSchema>;

